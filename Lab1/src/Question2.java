public class Question2 {

    public static void main(String[] args) {
        // Declaring one variable of each of the primitives
        byte byteValue = 100;
        short shortValue = 20000;
        int intValue = 350000;
        long longValue = 9000000000L; // Lsuffix nedded - value exceeds in
        float floatValue = 3.14f;    // f suffix needed for float literals
        double doubleValue = 3.141159265;
        char charValue = 'J';
        boolean booleanValue = true;

        // Printing every variable on its own, labelled with its type name
        System.out.println("Byte Value: " + byteValue);
        System.out.println("Short Value: " + shortValue);
        System.out.println("Int Value: " + intValue);
        System.out.println("Long Value: " + longValue);
        System.out.println("Float Value: " + floatValue);
        System.out.println("Double Value: " + doubleValue);
        System.out.println("Char Value: " + charValue);
        System.out.println("Boolean Value: " + booleanValue);
    }
    
}

